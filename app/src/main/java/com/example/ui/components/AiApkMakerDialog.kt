@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AiApkMakerDialog(
    onDismiss: () -> Unit,
    onAttachApkToChat: (Uri, String) -> Unit
) {
    val context = LocalContext.current
    val clipboardManager = LocalClipboardManager.current
    val coroutineScope = rememberCoroutineScope()

    var selectedTab by remember { java.util.concurrent.atomic.AtomicInteger(0).let { mutableIntStateOf(0) } }

    // App Metadata State
    var appTitle by remember { mutableStateOf("Smart Habit Tracker Pro") }
    var packageName by remember { mutableStateOf("com.aistudio.habittracker.app") }
    var versionCode by remember { mutableStateOf("1.0.0") }
    var appCategory by remember { mutableStateOf("Productivity") }
    var appDescription by remember { mutableStateOf("Build a modern Material 3 habit tracker app with local Room database, streak statistics, dynamic light/dark themes, and push notifications.") }
    var designStyle by remember { mutableStateOf("Material 3 Modern") }
    var architectureMode by remember { mutableStateOf("MVVM + Clean Architecture") }

    // Code & Visual UI State
    var generatedCode by remember {
        mutableStateOf(
            """
            // Generated by AI APK Studio (Jetpack Compose + Room)
            package com.aistudio.habittracker
            
            import androidx.compose.foundation.layout.*
            import androidx.compose.material3.*
            import androidx.compose.runtime.*
            import androidx.compose.ui.Modifier
            import androidx.compose.ui.unit.dp
            
            @Composable
            fun MainHabitScreen(viewModel: HabitViewModel) {
                val habits by viewModel.habits.collectAsState()
                Scaffold(
                    topBar = { TopAppBar(title = { Text("Smart Habit Tracker") }) },
                    floatingActionButton = {
                        FloatingActionButton(onClick = { viewModel.addNewHabit() }) {
                            Icon(Icons.Default.Add, contentDescription = "Add")
                        }
                    }
                ) { innerPadding ->
                    HabitList(habits = habits, modifier = Modifier.padding(innerPadding))
                }
            }
            """.trimIndent()
        )
    }

    // Plugin Toggles State
    var enableFirebase by remember { mutableStateOf(true) }
    var enableSupabase by remember { mutableStateOf(false) }
    var enableAdMob by remember { mutableStateOf(true) }
    var enableGoogleMaps by remember { mutableStateOf(false) }
    var enableCameraScanner by remember { mutableStateOf(true) }
    var enableRoomDb by remember { mutableStateOf(true) }
    var enableGeminiSdk by remember { mutableStateOf(true) }

    // Build State
    var buildType by remember { mutableStateOf("Signed Release APK (.apk)") }
    var isBuilding by remember { mutableStateOf(false) }
    var currentBuildStep by remember { mutableStateOf(0) }
    var isApkReady by remember { mutableStateOf(false) }
    var buildLogs by remember { mutableStateOf(listOf<String>()) }

    // Store Publishing Generator State
    var storeShortDesc by remember { mutableStateOf("Track your daily habits, set goals, and achieve personal growth with AI insights.") }
    var privacyPolicyText by remember { mutableStateOf("This app values user privacy. All habit data is stored locally using Room Database.") }

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            modifier = Modifier
                .fillMaxSize()
                .padding(12.dp),
            shape = RoundedCornerShape(24.dp),
            color = MaterialTheme.colorScheme.surface,
            tonalElevation = 6.dp
        ) {
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(14.dp)
            ) {
                // Header Bar
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Box(
                            modifier = Modifier
                                .size(38.dp)
                                .clip(CircleShape)
                                .background(Color(0xFF059669).copy(alpha = 0.15f)),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.Android,
                                contentDescription = null,
                                tint = Color(0xFF059669)
                            )
                        }
                        Spacer(modifier = Modifier.width(10.dp))
                        Column {
                            Row(verticalAlignment = Alignment.CenterVertically) {
                                Text(
                                    text = "📱 AI APK Studio & Development Platform",
                                    style = MaterialTheme.typography.titleMedium,
                                    fontWeight = FontWeight.Bold
                                )
                                Spacer(modifier = Modifier.width(6.dp))
                                Badge(containerColor = Color(0xFF10A37F)) {
                                    Text("PRO 9.3", color = Color.White, fontSize = 10.sp)
                                }
                            }
                            Text(
                                text = "প্রম্পট থেকে ফুল অ্যান্ড্রয়েড অ্যাপ জেনারেশন, বিল্ড ও সোর্স কোড এক্সপোর্ট",
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                    }

                    IconButton(onClick = onDismiss) {
                        Icon(Icons.Default.Close, contentDescription = "Close")
                    }
                }

                Spacer(modifier = Modifier.height(10.dp))

                // Navigation Tabs
                ScrollableTabRow(
                    selectedTabIndex = selectedTab,
                    edgePadding = 0.dp,
                    containerColor = Color.Transparent,
                    contentColor = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Tab(
                        selected = selectedTab == 0,
                        onClick = { selectedTab = 0 },
                        text = { Text("🚀 প্রম্পট টু অ্যাপ", fontSize = 12.sp) }
                    )
                    Tab(
                        selected = selectedTab == 1,
                        onClick = { selectedTab = 1 },
                        text = { Text("💻 UI ও কোড স্টুডিও", fontSize = 12.sp) }
                    )
                    Tab(
                        selected = selectedTab == 2,
                        onClick = { selectedTab = 2 },
                        text = { Text("🔌 প্লাগইন ও ব্যাকএন্ড", fontSize = 12.sp) }
                    )
                    Tab(
                        selected = selectedTab == 3,
                        onClick = { selectedTab = 3 },
                        text = { Text("📦 APK/AAB বিল্ডার", fontSize = 12.sp) }
                    )
                    Tab(
                        selected = selectedTab == 4,
                        onClick = { selectedTab = 4 },
                        text = { Text("📢 প্লে স্টোর পাবলিশিং", fontSize = 12.sp) }
                    )
                }

                HorizontalDivider(modifier = Modifier.padding(vertical = 10.dp))

                // Tab Content Body
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth()
                ) {
                    when (selectedTab) {
                        0 -> PromptToAppTab(
                            appTitle = appTitle,
                            onTitleChange = { appTitle = it },
                            packageName = packageName,
                            onPackageChange = { packageName = it },
                            versionCode = versionCode,
                            onVersionChange = { versionCode = it },
                            appCategory = appCategory,
                            onCategoryChange = { appCategory = it },
                            appDescription = appDescription,
                            onDescriptionChange = { appDescription = it },
                            designStyle = designStyle,
                            onDesignStyleChange = { designStyle = it },
                            architectureMode = architectureMode,
                            onArchitectureChange = { architectureMode = it },
                            onGenerateClick = {
                                selectedTab = 1
                            }
                        )

                        1 -> CodeAndUiStudioTab(
                            generatedCode = generatedCode,
                            onCodeChange = { generatedCode = it },
                            appTitle = appTitle,
                            designStyle = designStyle,
                            onCopyCode = {
                                clipboardManager.setText(AnnotatedString(generatedCode))
                            }
                        )

                        2 -> PluginsAndBackendTab(
                            enableFirebase = enableFirebase,
                            onFirebaseToggle = { enableFirebase = it },
                            enableSupabase = enableSupabase,
                            onSupabaseToggle = { enableSupabase = it },
                            enableAdMob = enableAdMob,
                            onAdMobToggle = { enableAdMob = it },
                            enableGoogleMaps = enableGoogleMaps,
                            onGoogleMapsToggle = { enableGoogleMaps = it },
                            enableCameraScanner = enableCameraScanner,
                            onCameraToggle = { enableCameraScanner = it },
                            enableRoomDb = enableRoomDb,
                            onRoomToggle = { enableRoomDb = it },
                            enableGeminiSdk = enableGeminiSdk,
                            onGeminiToggle = { enableGeminiSdk = it }
                        )

                        3 -> BuildApkTab(
                            appTitle = appTitle,
                            packageName = packageName,
                            buildType = buildType,
                            onBuildTypeChange = { buildType = it },
                            isBuilding = isBuilding,
                            currentBuildStep = currentBuildStep,
                            isApkReady = isApkReady,
                            buildLogs = buildLogs,
                            onStartBuild = {
                                isBuilding = true
                                isApkReady = false
                                currentBuildStep = 1
                                buildLogs = listOf("⚡ [AI Engine] Initializing Gradle Wrapper (Version 9.3.1)...")

                                coroutineScope.launch {
                                    delay(500)
                                    buildLogs = buildLogs + "📦 [KSP Engine] Parsing Room entities & Kotlin serialization schemas..."
                                    currentBuildStep = 2

                                    delay(700)
                                    buildLogs = buildLogs + "🎨 [Compose Engine] Compiling Material 3 composables & bytecode..."
                                    currentBuildStep = 3

                                    delay(800)
                                    buildLogs = buildLogs + "🔐 [Signer Engine] Signing build package with RSA-2048 certificate..."
                                    currentBuildStep = 4

                                    delay(600)
                                    buildLogs = buildLogs + "✅ BUILD SUCCESSFUL in 2.6s"
                                    buildLogs = buildLogs + "🎉 Target Created: $appTitle-v$versionCode.apk (14.8 MB)"

                                    isBuilding = false
                                    isApkReady = true
                                }
                            },
                            onDownloadApk = {
                                try {
                                    val intent = Intent(Intent.ACTION_SEND).apply {
                                        type = "application/vnd.android.package-archive"
                                        putExtra(Intent.EXTRA_SUBJECT, "$appTitle - APK Build Download")
                                        putExtra(
                                            Intent.EXTRA_TEXT,
                                            "📱 AI Generated App Download:\nName: $appTitle\nPackage: $packageName\nVersion: $versionCode\n\nBuild Status: Certified Signed Release APK Ready!"
                                        )
                                    }
                                    context.startActivity(Intent.createChooser(intent, "Download / Share $appTitle.apk"))
                                } catch (e: Exception) {
                                    e.printStackTrace()
                                }
                                android.widget.Toast.makeText(
                                    context,
                                    "✅ $appTitle.apk সফলভাবে ডাউনলোড ও সেভ হয়েছে!",
                                    android.widget.Toast.LENGTH_LONG
                                ).show()

                                val apkUri = Uri.parse("content://ai_generated_$packageName.apk")
                                onAttachApkToChat(apkUri, "$appTitle-v$versionCode.apk")
                                onDismiss()
                            },
                            onExportZip = {
                                try {
                                    val intent = Intent(Intent.ACTION_SEND).apply {
                                        type = "application/zip"
                                        putExtra(Intent.EXTRA_SUBJECT, "$appTitle - Source Code ZIP")
                                        putExtra(
                                            Intent.EXTRA_TEXT,
                                            "📦 Android Studio Project Source Code ZIP:\nApp Name: $appTitle\nArchitecture: MVVM + Clean Architecture\nUI: Jetpack Compose"
                                        )
                                    }
                                    context.startActivity(Intent.createChooser(intent, "Download $appTitle Source Code ZIP"))
                                } catch (e: Exception) {
                                    e.printStackTrace()
                                }
                                android.widget.Toast.makeText(
                                    context,
                                    "📦 $appTitle সোর্স কোড ZIP ডাউনলোড সম্পন্ন হয়েছে!",
                                    android.widget.Toast.LENGTH_LONG
                                ).show()

                                val zipUri = Uri.parse("content://chatgpt_app_source_project.zip")
                                onAttachApkToChat(zipUri, "${appTitle}_SourceCode.zip")
                                onDismiss()
                            }
                        )

                        4 -> PlayStorePublishingTab(
                            appTitle = appTitle,
                            shortDesc = storeShortDesc,
                            onShortDescChange = { storeShortDesc = it },
                            privacyPolicy = privacyPolicyText,
                            onPrivacyPolicyChange = { privacyPolicyText = it },
                            onCopyStoreDetails = {
                                val details = "App Title: $appTitle\nShort Description: $storeShortDesc\nPrivacy Policy: $privacyPolicyText"
                                clipboardManager.setText(AnnotatedString(details))
                            }
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun PromptToAppTab(
    appTitle: String,
    onTitleChange: (String) -> Unit,
    packageName: String,
    onPackageChange: (String) -> Unit,
    versionCode: String,
    onVersionChange: (String) -> Unit,
    appCategory: String,
    onCategoryChange: (String) -> Unit,
    appDescription: String,
    onDescriptionChange: (String) -> Unit,
    designStyle: String,
    onDesignStyleChange: (String) -> Unit,
    architectureMode: String,
    onArchitectureChange: (String) -> Unit,
    onGenerateClick: () -> Unit
) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(14.dp)
    ) {
        Card(
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f)),
            shape = RoundedCornerShape(16.dp)
        ) {
            Column(
                modifier = Modifier.padding(12.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Text("📝 অ্যাপ প্রম্পট ও আইডিয়া వివరণ", fontWeight = FontWeight.Bold, style = MaterialTheme.typography.titleSmall)

                OutlinedTextField(
                    value = appDescription,
                    onValueChange = onDescriptionChange,
                    label = { Text("কি ধরণের অ্যান্ড্রয়েড অ্যাপ তৈরি করতে চান?") },
                    modifier = Modifier.fillMaxWidth(),
                    minLines = 3,
                    maxLines = 5,
                    shape = RoundedCornerShape(12.dp)
                )

                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    val quickPrompts = listOf("Habit Tracker", "E-Commerce App", "AI Chat Bot", "Note Saver")
                    quickPrompts.forEach { p ->
                        SuggestionChip(
                            onClick = { onDescriptionChange("Build a high performance $p with local database and Material 3 UI.") },
                            label = { Text(p, fontSize = 11.sp) }
                        )
                    }
                }
            }
        }

        Card(
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f)),
            shape = RoundedCornerShape(16.dp)
        ) {
            Column(
                modifier = Modifier.padding(12.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Text("⚙️ প্রজেক্ট ও প্যাকেজ কনফিগারেশন", fontWeight = FontWeight.Bold, style = MaterialTheme.typography.titleSmall)

                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedTextField(
                        value = appTitle,
                        onValueChange = onTitleChange,
                        label = { Text("App Name") },
                        modifier = Modifier.weight(1f),
                        singleLine = true,
                        shape = RoundedCornerShape(12.dp)
                    )
                    OutlinedTextField(
                        value = versionCode,
                        onValueChange = onVersionChange,
                        label = { Text("Version") },
                        modifier = Modifier.width(90.dp),
                        singleLine = true,
                        shape = RoundedCornerShape(12.dp)
                    )
                }

                OutlinedTextField(
                    value = packageName,
                    onValueChange = onPackageChange,
                    label = { Text("Package ID (Unique)") },
                    modifier = Modifier.fillMaxWidth(),
                    singleLine = true,
                    shape = RoundedCornerShape(12.dp)
                )
            }
        }

        // Category & Design Style
        Column {
            Text("🎨 ডিজাইন ও আর্কিটেকচার স্টাইল", fontWeight = FontWeight.Bold, style = MaterialTheme.typography.titleSmall)
            Spacer(modifier = Modifier.height(6.dp))

            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf("Material 3 Modern", "Minimalist Glass", "Neumorphism").forEach { style ->
                    FilterChip(
                        selected = designStyle == style,
                        onClick = { onDesignStyleChange(style) },
                        label = { Text(style, fontSize = 11.sp) }
                    )
                }
            }

            Spacer(modifier = Modifier.height(4.dp))

            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf("MVVM + Clean Architecture", "Simple StateFlow").forEach { arch ->
                    FilterChip(
                        selected = architectureMode == arch,
                        onClick = { onArchitectureChange(arch) },
                        label = { Text(arch, fontSize = 11.sp) }
                    )
                }
            }
        }

        Button(
            onClick = onGenerateClick,
            modifier = Modifier.fillMaxWidth(),
            colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF10A37F)),
            shape = RoundedCornerShape(14.dp)
        ) {
            Icon(Icons.Default.AutoAwesome, contentDescription = null, modifier = Modifier.size(18.dp))
            Spacer(modifier = Modifier.width(8.dp))
            Text("এআই দিয়ে ফুল প্রজেক্ট কোড ও UI জেনারেট করুন", fontWeight = FontWeight.Bold)
        }
    }
}

