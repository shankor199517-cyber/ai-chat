@Composable
private fun BuildApkTab(
    appTitle: String,
    packageName: String,
    buildType: String,
    onBuildTypeChange: (String) -> Unit,
    isBuilding: Boolean,
    currentBuildStep: Int,
    isApkReady: Boolean,
    buildLogs: List<String>,
    onStartBuild: () -> Unit,
    onDownloadApk: () -> Unit,
    onExportZip: () -> Unit
) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        Card(
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f)),
            shape = RoundedCornerShape(16.dp)
        ) {
            Column(
                modifier = Modifier.padding(12.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                Text("⚙️ বিল্ড টাইপ ও আউটপুট ফরম্যাট", fontWeight = FontWeight.Bold, style = MaterialTheme.typography.titleSmall)

                val types = listOf("Signed Release APK (.apk)", "Google Play Bundle (.aab)", "Debug APK (.apk)")
                types.forEach { type ->
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clickable { onBuildTypeChange(type) },
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        RadioButton(selected = buildType == type, onClick = { onBuildTypeChange(type) })
                        Text(type, fontSize = 12.sp)
                    }
                }
            }
        }

        Button(
            onClick = onStartBuild,
            enabled = !isBuilding,
            modifier = Modifier.fillMaxWidth(),
            colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF059669)),
            shape = RoundedCornerShape(14.dp)
        ) {
            if (isBuilding) {
                CircularProgressIndicator(modifier = Modifier.size(18.dp), color = Color.White, strokeWidth = 2.dp)
                Spacer(modifier = Modifier.width(8.dp))
                Text("বিল্ড হচ্ছে Step $currentBuildStep/4...")
            } else {
                Icon(Icons.Default.Build, contentDescription = null, modifier = Modifier.size(18.dp))
                Spacer(modifier = Modifier.width(8.dp))
                Text("এক ক্লিকে APK / AAB বিল্ড করুন", fontWeight = FontWeight.Bold)
            }
        }

        if (buildLogs.isNotEmpty()) {
            Card(
                colors = CardDefaults.cardColors(containerColor = Color(0xFF1E293B)),
                shape = RoundedCornerShape(12.dp),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(12.dp)) {
                    Text("Build Output Terminal", color = Color(0xFF10B981), fontWeight = FontWeight.Bold, fontFamily = FontFamily.Monospace, fontSize = 11.sp)
                    Spacer(modifier = Modifier.height(4.dp))
                    buildLogs.forEach { log ->
                        Text(text = "> $log", color = Color(0xFFE2E8F0), fontFamily = FontFamily.Monospace, fontSize = 11.sp)
                    }
                }
            }
        }

        if (isApkReady) {
            Card(
                colors = CardDefaults.cardColors(containerColor = Color(0xFF059669).copy(alpha = 0.12f)),
                border = androidx.compose.foundation.BorderStroke(1.5.dp, Color(0xFF059669)),
                shape = RoundedCornerShape(16.dp)
            ) {
                Column(
                    modifier = Modifier.padding(14.dp),
                    verticalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column {
                            Text("🎉 $appTitle Build Ready!", fontWeight = FontWeight.Bold, fontSize = 14.sp)
                            Text("Package: $packageName", fontSize = 11.sp, color = Color(0xFF059669))
                        }
                        Icon(Icons.Default.CheckCircle, contentDescription = null, tint = Color(0xFF059669), modifier = Modifier.size(28.dp))
                    }

                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        Button(
                            onClick = onDownloadApk,
                            modifier = Modifier.weight(1f),
                            colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF10A37F))
                        ) {
                            Icon(Icons.Default.Download, contentDescription = null, modifier = Modifier.size(16.dp))
                            Spacer(modifier = Modifier.width(4.dp))
                            Text("APK ডাউনলোড", fontSize = 12.sp)
                        }

                        Button(
                            onClick = onExportZip,
                            modifier = Modifier.weight(1f),
                            colors = ButtonDefaults.buttonColors(containerColor = MaterialTheme.colorScheme.tertiary)
                        ) {
                            Icon(Icons.Default.FolderZip, contentDescription = null, modifier = Modifier.size(16.dp))
                            Spacer(modifier = Modifier.width(4.dp))
                            Text("ZIP এক্সপোর্ট", fontSize = 12.sp)
                        }
                    }
                }
            }
        }
    }
}

